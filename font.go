func DrawChar8x16(fb Framebuffer, x, y int, ch rune, fg, bg color.RGBA) {
	bmp, exists := font8x16Data[ch]
	if !exists {
		bmp = font8x16Data['?']
	}

	transparentBg := bg.A == 0

	for row := 0; row < 16; row++ {
		rowVal := bmp[row]
		destY := y + row
		for col := 0; col < 8; col++ {
			destX := x + col
			bit := (rowVal & (0x80 >> col)) != 0
			if bit {
				fb.SetPixel(destX, destY, fg)
			} else if !transparentBg {
				fb.SetPixel(destX, destY, bg)
			}
		}
	}
}
